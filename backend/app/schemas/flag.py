from pydantic import BaseModel, Field

class Flag(BaseModel):
    """A feature flag as supplied by a client.

    Used as the create payload (and as the reference shape for a flag). It
    deliberately omits server-owned fields such as ``id`` and timestamps, which
    are generated by the database.

    Attributes:
        flag_key: Unique, client-supplied identifier for the flag.
        enabled: Master on/off switch. When ``False`` the flag evaluates off
            for every user regardless of rollout or targeting.
        rollout_percentage: Percentage of the eligible population that should
            see the flag. Constrained to ``0..100``; defaults to ``0``
            (off for everyone until explicitly ramped up).
        target_users: Optional explicit allow-list of user IDs. ``None`` means
            "no explicit targeting"; a set means "these users (plus any
            percentage rollout)". Duplicates are collapsed by the ``set`` type.
    """
    flag_key: str
    enabled: bool
    rollout_percentage: int = Field(default=0, ge=0, le=100)
    target_users: set[str] | None = None

class FlagUpdate(BaseModel):
    """Partial-update payload for an existing flag.

        Every field defaults to ``None``, so callers send only what they want to
        change. Because ``None`` is also the default for "not supplied", these
        models cannot express *"explicitly clear this field"* — see the caveats in
        the module README.

        Attributes:
            enabled: New master switch value, or ``None`` to leave unchanged.
            rollout_percentage: New rollout percentage (``0..100``), or ``None``
                to leave unchanged.
            target_users: New allow-list, or ``None`` to leave unchanged.
    """
    enabled: bool | None = None
    rollout_percentage: int | None = Field(default=None, ge=0, le=100)
    target_users: set[str] | None = None

class EvalRequest(BaseModel):
    """Input to the flag-evaluation endpoint.

    Asks "should ``user_id`` see ``flag_key`` right now?" — the answer is
    computed, not stored.

    Attributes:
        flag_key: The flag to evaluate.
        user_id: The user whose exposure is being decided. Used for explicit
            targeting checks and as the rollout bucket key (so the same user
            gets a stable answer for a given flag).
    """
    flag_key: str
    user_id: str